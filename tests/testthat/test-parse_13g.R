cnames <- c("accession","filedDate", "submissionType", "amendmentNo",
            "previousAccession", "issuerCik", "issuerName", "issuerCusip",
            "securitiesClass", "eventDate", "soleVoting", "sharedVoting",
            "soleDispositive", "sharedDispositive", "aggregateShares",
            "classPercent", "reportingPersonTypes")

test_that("parse_13g parses a fresh SCHEDULE 13G (issuerCusips wrapper)", {
    new_sgml_format <- test_path("fixtures/sgml/0000092230-26-000041.txt")
    results <- parse_13g(new_sgml_format)
    cresults <- colnames(results)
    expect_equal(cresults, cnames)
    expect_equal(results$accession, "0000092230-26-000041")
    expect_equal(results$filedDate, as.Date("2026-04-20"))
    expect_equal(results$submissionType, "SCHEDULE 13G")
    expect_true(is.na(results$amendmentNo))
    expect_true(is.na(results$previousAccession))
    expect_equal(results$issuerCik, "0001771146")
    expect_equal(results$issuerName, "ETF Opportunities Trust")
    expect_equal(results$issuerCusip, "26923Q416")
    expect_equal(results$securitiesClass, "Exchange Traded Fund")
    expect_equal(results$eventDate, as.Date("2026-03-31"))
    expect_equal(results$soleVoting, 0)
    expect_equal(results$sharedVoting, 0)
    expect_equal(results$soleDispositive, 297117)
    expect_equal(results$sharedDispositive, 0)
    expect_equal(results$aggregateShares, 297117)
    expect_equal(results$classPercent, 8.6)
    expect_equal(results$reportingPersonTypes, "IA,HC")
})

